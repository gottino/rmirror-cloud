"""Fail when backend/.env.example drifts from app/config.py Settings.

The template is generated by scripts/generate_env_example.py; regenerate it with
`python scripts/generate_env_example.py` after changing Settings.
"""

import importlib.util
import re
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
SCRIPT = BACKEND_DIR / "scripts" / "generate_env_example.py"


def _load_generator():
    spec = importlib.util.spec_from_file_location("generate_env_example", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_env_example_is_current(capsys):
    generator = _load_generator()
    assert generator.main(["--check"]) == 0, capsys.readouterr().out


def test_env_example_lists_exactly_the_settings_fields():
    from app.config import Settings

    text = (BACKEND_DIR / ".env.example").read_text()
    names = set(re.findall(r"^(?:# )?([A-Z][A-Z0-9_]*)=", text, flags=re.M))
    assert names == {name.upper() for name in Settings.model_fields}


def test_env_example_has_no_real_defaults_for_secrets():
    text = (BACKEND_DIR / ".env.example").read_text()
    assert "DEBUG=false" in text
    assert re.search(r"^SECRET_KEY=change-me", text, flags=re.M)
